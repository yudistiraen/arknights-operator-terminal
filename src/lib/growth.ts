import {
  BATTLE_RECORDS,
  EXP_TO_NEXT_LEVEL,
  LMD_ITEM_ID,
  LMD_TO_NEXT_LEVEL,
  MAX_LEVEL,
  PROMOTION_LMD,
  type BattleRecord,
} from '../data/operatorGrowth'
import operatorCostsData from '../data/operatorCosts.json'

export interface MaterialCost {
  id: string
  count: number
}

interface OperatorCosts {
  promotion: MaterialCost[][]   // [Elite 1, Elite 2]
  skillLevel: MaterialCost[][]  // [Lv1→2, …, Lv6→7], shared by every skill
  mastery: MaterialCost[][][]   // per skill: [M1, M2, M3]
  modules: ModuleCosts[]
}

export interface ModuleCosts {
  code: string                  // e.g. 'MAR-X', matches OperatorModule.code
  unlockLevel: number           // Elite 2 level the module unlocks at
  stages: MaterialCost[][]      // [Stage 1, Stage 2, Stage 3]
}

// Generated by scripts/growth/gen-growth-data.mjs, keyed by operator name.
const OPERATOR_COSTS = operatorCostsData as Record<string, OperatorCosts>

export interface GrowthRange {
  current: number
  target: number
}

export const MAX_SKILL_LEVEL = 7
// Skill levels 5–7 unlock at Elite 1; masteries need Elite 2 and Skill Level 7.
const SKILL_LEVEL_CAP_AT_ELITE_0 = 4
const MASTERY_ELITE = 2

export interface GrowthPoint {
  elite: number
  level: number
}

export function maxLevelsFor(rarity: number): number[] {
  return MAX_LEVEL[rarity - 1] ?? MAX_LEVEL[0]
}

export function maxEliteFor(rarity: number): number {
  return maxLevelsFor(rarity).length - 1
}

export function maxPointFor(rarity: number): GrowthPoint {
  const elite = maxEliteFor(rarity)
  return { elite, level: maxLevelsFor(rarity)[elite] }
}

// Pulls a point back inside what the rarity allows (elite cap, then that elite's level cap).
export function clampPoint(rarity: number, point: GrowthPoint): GrowthPoint {
  const elite = Math.min(Math.max(point.elite, 0), maxEliteFor(rarity))
  const level = Math.min(Math.max(Math.round(point.level) || 1, 1), maxLevelsFor(rarity)[elite])
  return { elite, level }
}

export function comparePoints(left: GrowthPoint, right: GrowthPoint): number {
  return left.elite !== right.elite ? left.elite - right.elite : left.level - right.level
}

// Sums a per-level table from `from` to `to`. Crossing an elite phase means leveling to that
// phase's cap first — promotion resets the level to 1, so each phase is summed on its own.
function sumLevelTable(table: number[][], rarity: number, from: GrowthPoint, to: GrowthPoint): number {
  if (comparePoints(from, to) >= 0) return 0
  const levelCaps = maxLevelsFor(rarity)
  let total = 0
  for (let elite = from.elite; elite <= to.elite; elite++) {
    const startLevel = elite === from.elite ? from.level : 1
    const endLevel = elite === to.elite ? to.level : levelCaps[elite]
    for (let level = startLevel; level < endLevel; level++) {
      total += table[elite][level - 1]
    }
  }
  return total
}

export function expBetween(rarity: number, from: GrowthPoint, to: GrowthPoint): number {
  return sumLevelTable(EXP_TO_NEXT_LEVEL, rarity, from, to)
}

// Promotion materials for every elite phase entered on the way, plus LMD for both the level-ups
// and the promotions. LMD is listed first so it reads as the baseline cost.
export function materialsBetween(operatorName: string, rarity: number, from: GrowthPoint, to: GrowthPoint): MaterialCost[] {
  if (comparePoints(from, to) >= 0) return []
  const counts = new Map<string, number>()
  const add = (id: string, count: number) => { if (count > 0) counts.set(id, (counts.get(id) ?? 0) + count) }

  add(LMD_ITEM_ID, sumLevelTable(LMD_TO_NEXT_LEVEL, rarity, from, to))
  for (let elite = from.elite + 1; elite <= to.elite; elite++) {
    add(LMD_ITEM_ID, PROMOTION_LMD[rarity - 1]?.[elite - 1] ?? 0)
    OPERATOR_COSTS[operatorName]?.promotion[elite - 1]?.forEach(({ id, count }) => add(id, count))
  }
  return [...counts].map(([id, count]) => ({ id, count }))
}

// Highest skill level reachable at an elite phase — 1 for 1★/2★, which have no skill levels.
export function maxSkillLevelFor(operatorName: string, elite: number): number {
  const steps = OPERATOR_COSTS[operatorName]?.skillLevel.length ?? 0
  if (steps === 0) return 1
  return Math.min(steps + 1, elite >= 1 ? MAX_SKILL_LEVEL : SKILL_LEVEL_CAP_AT_ELITE_0)
}

// Masteries each skill offers (3 for 4★ and up, 0 below), in skill order.
export function masteryCountsFor(operatorName: string): number[] {
  return OPERATOR_COSTS[operatorName]?.mastery.map(steps => steps.length) ?? []
}

export function canMaster(target: GrowthPoint, skillLevelTarget: number): boolean {
  return target.elite >= MASTERY_ELITE && skillLevelTarget >= MAX_SKILL_LEVEL
}

export function clampRange(range: GrowthRange, min: number, max: number): GrowthRange {
  const clamp = (value: number) => Math.min(Math.max(Math.round(value) || min, min), max)
  return { current: clamp(range.current), target: clamp(range.target) }
}

// Skill level materials (shared by all skills) plus each skill's mastery materials. Masteries
// only count when the plan reaches Elite 2 at Skill Level 7, matching the in-game unlock.
export function skillMaterialsBetween(
  operatorName: string,
  target: GrowthPoint,
  skillLevel: GrowthRange,
  masteries: GrowthRange[],
): MaterialCost[] {
  const costs = OPERATOR_COSTS[operatorName]
  if (!costs) return []
  const lists: MaterialCost[][] = []
  for (let level = skillLevel.current; level < skillLevel.target; level++) lists.push(costs.skillLevel[level - 1] ?? [])
  if (canMaster(target, skillLevel.target)) {
    masteries.forEach((mastery, skillIndex) => {
      for (let rank = mastery.current; rank < mastery.target; rank++) lists.push(costs.mastery[skillIndex]?.[rank] ?? [])
    })
  }
  return mergeMaterials(...lists)
}

// Every module with an upgrade cost (the default "Original" module has none), in gamedata order.
export function modulesFor(operatorName: string): ModuleCosts[] {
  return OPERATOR_COSTS[operatorName]?.modules ?? []
}

export function canUnlockModule(target: GrowthPoint, module: ModuleCosts): boolean {
  return target.elite >= MASTERY_ELITE && target.level >= module.unlockLevel
}

// Stage materials for each module, indexed like modulesFor(); a module only counts when the
// plan's target reaches its Elite 2 unlock level.
export function moduleMaterialsBetween(operatorName: string, target: GrowthPoint, modules: GrowthRange[]): MaterialCost[] {
  const lists: MaterialCost[][] = []
  modulesFor(operatorName).forEach((module, moduleIndex) => {
    const range = modules[moduleIndex]
    if (!range || !canUnlockModule(target, module)) return
    for (let stage = range.current; stage < range.target; stage++) lists.push(module.stages[stage] ?? [])
  })
  return mergeMaterials(...lists)
}

export function mergeMaterials(...lists: MaterialCost[][]): MaterialCost[] {
  const counts = new Map<string, number>()
  lists.flat().forEach(({ id, count }) => counts.set(id, (counts.get(id) ?? 0) + count))
  return [...counts].map(([id, count]) => ({ id, count }))
}

export interface RecordAllocation {
  record: BattleRecord
  count: number
}

// Greedy fill, highest tier first; the lowest tier rounds up so the target is always reached.
export function allocateRecords(exp: number): { allocations: RecordAllocation[]; overflow: number } {
  let remaining = exp
  const allocations = BATTLE_RECORDS.map((record, index) => {
    const isLowestTier = index === BATTLE_RECORDS.length - 1
    const count = isLowestTier ? Math.ceil(remaining / record.exp) : Math.floor(remaining / record.exp)
    remaining -= count * record.exp
    return { record, count: Math.max(count, 0) }
  })
  return { allocations, overflow: -Math.min(remaining, 0) }
}
