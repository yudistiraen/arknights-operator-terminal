// Builds the Growth Planner's data from the EN gamedata (ArknightsAssets/ArknightsGamedata):
//   src/data/operatorGrowth.ts   — EXP / LMD per level, level caps, promotion LMD, Battle Records
//   src/data/operatorCosts.json  — per roster operator: promotion, skill level, mastery and module materials
//
// Operators are matched to character_table by display name, collected from every `name:` string
// in src/data/operators/*.ts (alters included); names that aren't a playable character are skipped.
//
// Usage: node scripts/growth/gen-growth-data.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const operatorsDir = path.join(projectRoot, 'src/data/operators')
const gamedataBase = 'https://raw.githubusercontent.com/ArknightsAssets/ArknightsGamedata/master/en/gamedata/excel'
const NON_OPERATOR_PROFESSIONS = new Set(['TOKEN', 'TRAP'])
// character_table names that the roster spells differently.
const ROSTER_NAME_BY_TABLE_NAME = {
  "'Justice Knight'": 'Justice Knight',
  'Sakiko Togawa': 'Togawa Sakiko',
}

async function fetchTable(name) {
  const response = await fetch(`${gamedataBase}/${name}.json`)
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`)
  return response.json()
}

function collectRosterNames() {
  const names = new Set()
  const namePattern = /name:\s*(['"`])((?:\\.|(?!\1).)*)\1/g
  for (const file of readdirSync(operatorsDir).filter(file => file.endsWith('.ts'))) {
    const source = readFileSync(path.join(operatorsDir, file), 'utf8')
    for (const match of source.matchAll(namePattern)) names.add(match[2].replace(/\\(.)/g, '$1'))
  }
  return names
}

const [gameConst, characterTable, itemTable, uniequipTable] = await Promise.all([
  fetchTable('gamedata_const'),
  fetchTable('character_table'),
  fetchTable('item_table'),
  fetchTable('uniequip_table'),
])

// --- operatorGrowth.ts ---
const trimRow = row => row.filter(value => value > 0)
const formatRows = rows => rows.map(row => `  [${trimRow(row).join(', ')}],`).join('\n')
const battleRecords = Object.values(itemTable.expItems)
  .map(({ id, gainExp }) => ({ id, gainExp, item: itemTable.items[id] }))
  .sort((left, right) => right.gainExp - left.gainExp)
  .map(({ id, gainExp, item }) =>
    `  { id: '${id}', name: '${item.name}', exp: ${gainExp}, rarity: ${Number(String(item.rarity).replace('TIER_', '')) || 0}, icon: '${item.iconId}' },`)

writeFileSync(path.join(projectRoot, 'src/data/operatorGrowth.ts'), `// Generated by scripts/growth/gen-growth-data.mjs from the EN gamedata (gamedata_const.json,
// item_table.json). Shared by every operator — rarity only sets the level caps and promotion LMD.

// EXP_TO_NEXT_LEVEL[elite][level - 1] = EXP needed to go from \`level\` to \`level + 1\` at that elite phase.
export const EXP_TO_NEXT_LEVEL: number[][] = [
${formatRows(gameConst.characterExpMap)}
]

// Same indexing as EXP_TO_NEXT_LEVEL, in LMD.
export const LMD_TO_NEXT_LEVEL: number[][] = [
${formatRows(gameConst.characterUpgradeCostMap)}
]

// MAX_LEVEL[rarity - 1][elite]; the inner array's length is how many elite phases that rarity has.
export const MAX_LEVEL: number[][] = ${JSON.stringify(gameConst.maxLevel)}

// PROMOTION_LMD[rarity - 1][elite - 1] = LMD to promote into that elite phase.
export const PROMOTION_LMD: number[][] = ${JSON.stringify(gameConst.evolveGoldCost.map(trimRow))}

export const LMD_ITEM_ID = '4001'

export interface BattleRecord {
  id: string
  name: string
  exp: number
  rarity: number
  icon: string
}

// Highest tier first — the planner fills EXP greedily in this order.
export const BATTLE_RECORDS: BattleRecord[] = [
${battleRecords.join('\n')}
]
`)

// --- operatorCosts.json ---
// evolveCost / levelUpCostCond / allSkillLvlup come back as `{}` instead of an array when empty
// (e.g. 3★ Elite 1 costs only LMD, 3★ skills have no masteries).
const asArray = value => Array.isArray(value) ? value : []
const toCosts = costs => asArray(costs).map(({ id, count }) => ({ id, count }))

// Modules by character id. Original (default) modules have no cost and are skipped.
const modulesByCharId = {}
for (const equip of Object.values(uniequipTable.equipDict)) {
  if (!equip.itemCost) continue
  const stages = Object.keys(equip.itemCost).sort().map(stage => toCosts(equip.itemCost[stage]))
  ;(modulesByCharId[equip.charId] ??= []).push({
    code: [equip.typeName1, equip.typeName2].filter(Boolean).join('-'),
    unlockLevel: equip.unlockLevel,
    stages,
  })
}

const rosterNames = collectRosterNames()
const operatorCosts = {}
for (const [charId, character] of Object.entries(characterTable)) {
  const rosterName = ROSTER_NAME_BY_TABLE_NAME[character.name] ?? character.name
  if (NON_OPERATOR_PROFESSIONS.has(character.profession) || !rosterNames.has(rosterName)) continue
  // First entry wins for duplicate names — the original character precedes later re-releases.
  if (operatorCosts[rosterName]) continue
  operatorCosts[rosterName] = {
    // [Elite 1, Elite 2]
    promotion: character.phases.slice(1).map(phase => toCosts(phase.evolveCost)),
    // [Lv1→2, …, Lv6→7], shared by all of the operator's skills
    skillLevel: asArray(character.allSkillLvlup).map(step => toCosts(step.lvlUpCost)),
    // Per skill: [M1, M2, M3]
    mastery: asArray(character.skills).map(skill => asArray(skill.levelUpCostCond).map(step => toCosts(step.levelUpCost))),
    // Per module: code (e.g. MAR-X), Elite 2 level it unlocks at, and [Stage 1, Stage 2, Stage 3] costs
    modules: modulesByCharId[charId] ?? [],
  }
}
writeFileSync(path.join(projectRoot, 'src/data/operatorCosts.json'), JSON.stringify(operatorCosts) + '\n')

console.log(`operatorGrowth.ts written; costs for ${Object.keys(operatorCosts).length} operators`)
